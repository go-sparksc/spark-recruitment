-- PRD decision 120. The interview sheets carry a nine-question transcript and
-- per-category notes from each of two interviewers. This is where those go.
--
-- Additive only. No backfill, and no existing row changes meaning:
--   - every existing InterviewResult gets note = NULL and recommendation = NULL,
--     which render nothing at all, and scoreIsComputed = false, which is exactly
--     what every row imported before this migration is — a verbatim average read
--     off the sheet. The default is the honest value, so there is nothing to
--     backfill and no window where a row means something it did not mean before;
--   - every existing InterviewCategoryScore gets note = NULL, likewise rendering
--     nothing;
--   - InterviewQuestion and InterviewAnswer start empty, so every applicant whose
--     notes were imported under the old single-column contract keeps rendering
--     from InterviewNotes.body exactly as they did.
-- So the day this deploys, every screen looks exactly as it did before.
--
-- InterviewNotes is deliberately untouched, including UNIQUE (applicantId). The
-- notes sheet is one shared notetaker's transcript, not a per-interviewer
-- judgement; the per-interviewer prose goes on InterviewResult, which has been
-- keyed (applicantId, interviewerName) since 20260820000000_first_round_interviews.
--
-- Generated by `prisma migrate diff`, then hand-finished below for the one CHECK
-- Prisma cannot express. It is asserted against the database by
-- prisma/checks/interview-transcript.ts.

