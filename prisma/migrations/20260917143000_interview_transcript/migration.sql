-- An ordinal is a position in the sheet, counted from the left. A negative one
-- could only come from a arithmetic slip in the commit path, and it would sort
-- the transcript wrongly rather than fail — the questions would render in an
-- order nobody chose, which reads as the interview having gone that way. Cheap
-- to refuse here, invisible if it ever happened.
ALTER TABLE "InterviewQuestion" ADD CONSTRAINT "InterviewQuestion_ordinal_nonneg"
    CHECK ("ordinal" >= 0);

-- Deliberately NOT constrained, recorded so the omission reads as a choice:
--
--   * `InterviewResult.scoreIsComputed` against `score`. There is no invariant
--     between them — any score can legitimately be either computed or verbatim,
--     and the flag records provenance rather than restricting a value.
--   * `InterviewResult.recommendation` against anything. Null is legal and
--     common, and means "this interviewer recorded none" in all three of the
--     ways it can arise (column unmapped, cell blank, value unreadable).
--   * `InterviewCategoryScore.note` against `points`. A note with no score is
--     already impossible: decision 59 writes no row at all for an unreadable
--     score, so there is no row for an orphaned note to live on. The importer
--     reports that case; the database cannot see it.
